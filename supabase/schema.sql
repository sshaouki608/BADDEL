-- BADDEL initial database schema
-- Run this script once in Supabase SQL Editor on a new project.
-- RLS is enabled on every user-facing table. Never expose service_role keys.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'مستخدم جديد',
  avatar_url text,
  wilaya text,
  municipality text,
  bio text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name_ar text not null unique,
  slug text not null unique,
  icon text,
  is_active boolean not null default true,
  sort_order int not null default 0
);

create table if not exists public.listings (
  id uuid primary key default gen_random_uuid(),
  seller_id uuid not null references public.profiles(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  title text not null check (char_length(title) between 3 and 120),
  description text not null default '',
  price_dzd numeric(14,2) check (price_dzd is null or price_dzd >= 0),
  listing_type text not null default 'sale' check (listing_type in ('sale','exchange','both')),
  item_condition text not null default 'good' check (item_condition in ('new','like_new','good','acceptable')),
  wilaya text not null,
  municipality text,
  status text not null default 'active' check (status in ('active','reserved','sold','exchanged','hidden','removed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.listing_images (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  image_url text not null,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  listing_id uuid not null references public.listings(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, listing_id)
);

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid references public.listings(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.conversation_members (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create table if not exists public.swap_offers (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  proposer_id uuid not null references public.profiles(id) on delete cascade,
  offered_listing_id uuid references public.listings(id) on delete set null,
  cash_difference_dzd numeric(14,2) check (cash_difference_dzd is null or cash_difference_dzd >= 0),
  note text,
  status text not null default 'pending' check (status in ('pending','accepted','rejected','withdrawn')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  listing_id uuid references public.listings(id) on delete cascade,
  reported_user_id uuid references public.profiles(id) on delete cascade,
  reason text not null,
  details text,
  status text not null default 'pending' check (status in ('pending','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now(),
  constraint reports_target_required check (listing_id is not null or reported_user_id is not null)
);

create index if not exists listings_browse_idx on public.listings(status, wilaya, category_id, created_at desc);
create index if not exists listings_seller_idx on public.listings(seller_id, created_at desc);
create index if not exists messages_conversation_idx on public.messages(conversation_id, created_at);
create index if not exists swap_offers_listing_idx on public.swap_offers(listing_id, created_at desc);

-- Create a profile automatically when a user signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), 'مستخدم جديد')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Enable row-level security everywhere.
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.listings enable row level security;
alter table public.listing_images enable row level security;
alter table public.favorites enable row level security;
alter table public.conversations enable row level security;
alter table public.conversation_members enable row level security;
alter table public.messages enable row level security;
alter table public.swap_offers enable row level security;
alter table public.reports enable row level security;

-- Profiles: public profile fields can be read; each user edits only their own.
create policy "Profiles are viewable" on public.profiles
for select using (true);
create policy "Users insert own profile" on public.profiles
for insert with check (auth.uid() = id);
create policy "Users update own profile" on public.profiles
for update using (auth.uid() = id) with check (auth.uid() = id);

-- Categories are visible to everyone; only trusted server/admin workflows should edit them.
create policy "Active categories are public" on public.categories
for select using (is_active = true);

-- Listings: public can browse active listings; owners manage their own.
create policy "Active listings are public" on public.listings
for select using (status = 'active' or auth.uid() = seller_id);
create policy "Users create own listings" on public.listings
for insert with check (auth.uid() = seller_id);
create policy "Owners update own listings" on public.listings
for update using (auth.uid() = seller_id) with check (auth.uid() = seller_id);
create policy "Owners delete own listings" on public.listings
for delete using (auth.uid() = seller_id);

-- Images follow visibility and ownership of their listing.
create policy "Listing images are public for active listings" on public.listing_images
for select using (
  exists (select 1 from public.listings l where l.id = listing_id and (l.status = 'active' or l.seller_id = auth.uid()))
);
create policy "Owners add listing images" on public.listing_images
for insert with check (
  exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = auth.uid())
);
create policy "Owners remove listing images" on public.listing_images
for delete using (
  exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = auth.uid())
);

-- Favorites are private to their owner.
create policy "Users view own favorites" on public.favorites
for select using (auth.uid() = user_id);
create policy "Users add own favorites" on public.favorites
for insert with check (auth.uid() = user_id);
create policy "Users remove own favorites" on public.favorites
for delete using (auth.uid() = user_id);

-- Conversation membership is private to participants.
create policy "Members view their conversations" on public.conversations
for select using (
  exists (select 1 from public.conversation_members cm where cm.conversation_id = id and cm.user_id = auth.uid())
);
-- No client-side INSERT policies for conversations or members yet.
-- Membership must be created by a trusted server-side workflow after verifying
-- the listing owner and the other participant. This prevents users joining
-- conversations they do not belong to.
create policy "Members view membership" on public.conversation_members
for select using (user_id = auth.uid());
create policy "Members read messages" on public.messages
for select using (
  exists (select 1 from public.conversation_members cm where cm.conversation_id = messages.conversation_id and cm.user_id = auth.uid())
);
create policy "Members send messages as themselves" on public.messages
for insert with check (
  sender_id = auth.uid()
  and exists (select 1 from public.conversation_members cm where cm.conversation_id = messages.conversation_id and cm.user_id = auth.uid())
);
-- Message edits are disabled initially. Add a narrowly scoped RPC later if needed.

-- Swap offers: proposer and listing owner can view; proposer creates and may withdraw.
create policy "Offer parties view offers" on public.swap_offers
for select using (
  proposer_id = auth.uid()
  or exists (select 1 from public.listings l where l.id = listing_id and l.seller_id = auth.uid())
);
create policy "Users create swap offers" on public.swap_offers
for insert with check (
  proposer_id = auth.uid()
  and exists (select 1 from public.listings l where l.id = listing_id and l.status = 'active' and l.seller_id <> auth.uid())
);
-- Offer status changes are disabled from direct client updates initially.
-- We will add secure accept/reject/withdraw actions with validation later.

-- Reports are private to their reporter; moderation will use a protected server/admin role.
create policy "Users view own reports" on public.reports
for select using (reporter_id = auth.uid());
create policy "Users submit reports" on public.reports
for insert with check (reporter_id = auth.uid());

